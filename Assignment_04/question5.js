// Question 5 — Menu Selection Using switch

let choice = 2; // Change this number to test different options (1-4)

console.log("Choice:", choice);

switch (choice) {
    case 1:
        console.log("Output: You selected Home");
        break;
    case 2:
        console.log("Output: You selected About");
        break;
    case 3:
        console.log("Output: You selected Services");
        break;
    case 4:
        console.log("Output: You selected Contact");
        break;
    default:
        console.log("Output: Invalid choice");
}
