// Question 1 — JavaScript Operators

let num1 = 10;
let num2 = 5;

// Arithmetic
console.log("--- Arithmetic ---");
console.log("Add:", num1 + num2);
console.log("Sub:", num1 - num2);
console.log("Mul:", num1 * num2);
console.log("Div:", num1 / num2);
console.log("Mod:", num1 % num2);

let a = 10;
a++;
console.log("Inc:", a);

let b = 5;
b--;
console.log("Dec:", b);

// Assignment
console.log("\n--- Assignment ---");
let result = 20;
console.log("Start:", result);

result += 10;
console.log("AddAssign:", result);

result -= 5;
console.log("SubAssign:", result);

result *= 2;
console.log("MulAssign:", result);

result /= 5;
console.log("DivAssign:", result);

// Comparison
console.log("\n--- Comparison ---");
console.log("Equal:", num1 == num2);
console.log("StrictEqual:", num1 === num2);
console.log("NotEqual:", num1 != num2);
console.log("StrictNotEqual:", num1 !== num2);
console.log("Greater:", num1 > num2);
console.log("Less:", num1 < num2);
console.log("GreaterOrEqual:", num1 >= num2);
console.log("LessOrEqual:", num1 <= num2);
