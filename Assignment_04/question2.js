// Student Grade Calculator

let marks = 59;

if (marks >= 90) {
    console.log("Marks:", marks);
    console.log("Grade: A");
}
else if (marks >= 80) {
    console.log("Marks:", marks);
    console.log("Grade: B");
}
else if (marks >= 70) {
    console.log("Marks:", marks);
    console.log("Grade: C");
}
else if (marks >= 60) {
    console.log("Marks:", marks);
    console.log("Grade: D");
}
else {
    console.log("Marks:", marks);
    console.log("Grade: F");
}