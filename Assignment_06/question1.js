// Question 1: Basic Array Methods


let fruits_name = ["mango", "banana", "orange", "cherry", "apple"];

// 1. Use length
console.log(fruits_name.length);

// 2. Use toString()
let fruits_to_string = fruits_name.toString();
console.log(fruits_to_string);

// 3. Use at() to access at least two elements
console.log(fruits_name.at(0));
console.log(fruits_name.at(3));

// 4. Use join()
console.log(fruits_name.join(" - "));


