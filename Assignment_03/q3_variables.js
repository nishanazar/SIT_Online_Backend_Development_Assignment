// Variable declarations
var studentName = "Ali";
let studentAge = 20;
const studentCountry = "Pakistan";

console.log("Variable using var:", studentName);
console.log("Variable using let:", studentAge);
console.log("Variable using const:", studentCountry);

// ------------------------------------------
// 1. String

let myName = "Nisha";
console.log("String value:", myName);
console.log("String type:", typeof myName);


// ------------------------------------------
// 2. Number

let num = 555;
console.log("String value:", num);
console.log("String type:", typeof num);



// ------------------------------------------
// 3. Boolean

let isStudent = true;

console.log("Boolean value:", isStudent);
console.log("Boolean type:", typeof isStudent);


// ------------------------------------------
// 4. Undefined

let result;

console.log("Undefined value:", result);
console.log("Undefined type:", typeof result);


// ------------------------------------------
// 5. Null


let middleName = null;

console.log("Null value:", middleName);
console.log("Null type:", typeof middleName);


// ------------------------------------------
// 6. Object

let student = {
    name: "Ali",
    age: 20,
    city: "Karachi"
};

console.log("Object value:", student);
console.log("Object type:", typeof student);


// ------------------------------------------
// 7. Array


let fruits = ["Apple", "Banana", "Mango"];

console.log("Array value:", fruits);
console.log("Array type:", typeof fruits);


// ------------------------------------------
// 8. Symbol

let studentId = Symbol("StudentID");

console.log("Symbol value:", studentId);
console.log("Symbol type:", typeof studentId);


// ------------------------------------------
// 9. BigInt

let bigNumber = 12345678901234567890n;

console.log("BigInt value:", bigNumber);
console.log("BigInt type:", typeof bigNumber);